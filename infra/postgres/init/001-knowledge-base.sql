-- Local compatibility schema inferred from confluence_workflow SQL callers.
-- The original upstream DDL/procedure is not included in the reference repo.
CREATE SCHEMA IF NOT EXISTS knowledge_base;

CREATE TABLE IF NOT EXISTS knowledge_base.documents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bot_id text NOT NULL,
    page_id text NOT NULL,
    title text,
    content text,
    content_hash text,
    version_number integer,
    source_link text,
    parent_id text,
    sync_status text,
    create_by text,
    create_at timestamptz,
    updated_by text,
    updated_at timestamptz,
    source_type text,
    is_deleted boolean NOT NULL DEFAULT false,
    CONSTRAINT documents_bot_page_unique UNIQUE (bot_id, page_id)
);

CREATE TABLE IF NOT EXISTS knowledge_base.sync_jobs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status text NOT NULL,
    started_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    total_processed integer NOT NULL DEFAULT 0,
    total_updated integer NOT NULL DEFAULT 0,
    total_deleted integer NOT NULL DEFAULT 0,
    logs text
);

-- Match the 11 arguments passed by AUTO/PARTIAL.
-- Upsert the current snapshot; this is not version-history storage.
CREATE OR REPLACE PROCEDURE knowledge_base.sp_sync_confluence_page(
    p_bot_id text, p_page_id text, p_title text, p_content text,
    p_source_link text, p_version integer, p_parent_id text,
    p_create_by text, p_create_at timestamptz,
    p_updated_by text, p_updated_at timestamptz
)
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO knowledge_base.documents (
        bot_id, page_id, title, content, content_hash, version_number,
        source_link, parent_id, sync_status, create_by, create_at,
        updated_by, updated_at, source_type, is_deleted
    ) VALUES (
        p_bot_id, p_page_id, p_title, p_content, md5(coalesce(p_content, '')),
        p_version, p_source_link, p_parent_id, 'SYNCED', p_create_by,
        p_create_at, p_updated_by, p_updated_at, 'CONFLUENCE', false
    ) ON CONFLICT (bot_id, page_id) DO UPDATE SET
        title = EXCLUDED.title,
        content = EXCLUDED.content,
        content_hash = EXCLUDED.content_hash,
        version_number = EXCLUDED.version_number,
        source_link = EXCLUDED.source_link,
        parent_id = EXCLUDED.parent_id,
        sync_status = EXCLUDED.sync_status,
        updated_by = EXCLUDED.updated_by,
        updated_at = EXCLUDED.updated_at,
        source_type = EXCLUDED.source_type,
        is_deleted = false;
END;
$$;
